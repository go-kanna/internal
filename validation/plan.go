// What kanna-validator writes, and what tells a Validate of its writing, which
// the next run of it may take away.
const (
	// DirectiveKey marks a struct kanna-validator writes Validate for.
	DirectiveKey = "validate"

	// OutputFile is the file kanna-validator writes the methods of a package
	// into.
	OutputFile = "validator_gen.go"

	// Generator is the name kanna-validator goes by in the header of what it
	// writes.
	Generator = "kanna-validator"
)

// What kanna-value writes, which gives an enum Validate.
const (
	enumKey         = "enum"
	valueOutputFile = "value_gen.go"
	valueGenerator  = "kanna-value"
)

// generatedHeader matches the header of a generated file, naming the tool and
// the release, if any, that wrote it.
var generatedHeader = regexp.MustCompile(`^// Code generated by ([^ .]+)(?: [^ ]+)?\. DO NOT EDIT\.$`)

// Field is a field with something to check.
type Field struct {
	scan.Field

	// Value is what generated code checks of the field.
	Value *Value
}

// Value is what the generated code checks of one value: a field, the value a
// pointer points to, or an element of a slice, array, or map.
type Value struct {
	typ types.Type

	// required reports blank for the zero value, and omitEmpty lets it past
	// the rest. zero is how to tell it.
	required, omitEmpty bool
	zero                zeroTest

	// checks are the other rules, each reported on its own.
	checks []check

	// nest calls the value's Validate method and nests what it reports under
	// the value's path.
	nest bool

	// nilable holds the selectors, from the value, of the embedded fields its
	// Validate is promoted through that may be nil, outermost first. nest
	// calls it only when none is: it would panic.
	nilable []string

	// pointee is what the rest of a pointer's rules check: what it points to,
	// when it is not nil.
	pointee *Value

	// elem checks each element of a slice or array, or each value of a map.
	elem *Value
}

// zeroTest is how generated code tells the zero value of a type.
type zeroTest int

const (
	// zeroString compares a string with "".
	zeroString zeroTest = iota
	// zeroNumber compares a number with 0.
	zeroNumber
	// zeroBool tests a bool for false.
	zeroBool
	// zeroNil compares a pointer, slice, map, interface, channel, or function
	// with nil. An empty slice or map that is not nil is not zero.
	zeroNil
	// zeroMethod calls the type's own IsZero method.
	zeroMethod
	// zeroComposite compares a comparable struct or array with its zero
	// literal.
	zeroComposite
)

// Planner holds what deciding the checks of a value needs besides its type.
type Planner struct {
	fset *token.FileSet

	// targets are the types this run generates Validate for, which have it
	// even before it is written.
	targets map[*types.TypeName]bool

	// rewritten are the import paths of the packages whose output this run
	// rewrites, where a Validate an earlier run generated may be about to go.
	rewritten map[string]bool

	// marks caches what marked has read.
	marks map[mark]bool
}

// mark is a directive on the declaration of a type.
type mark struct {
	obj *types.TypeName
	key string
}

// NewPlanner returns a Planner for one run of a generator. writes are the types
// the run generates Validate for, which have it even before it is written, and
// rewrites the import paths of the packages whose output of kanna-validator the
// run rewrites, where a Validate an earlier run generated may be about to go. A
// generator that writes no Validate passes neither: a type then has Validate as
// what is written and the marks on the declarations say.
func NewPlanner(fset *token.FileSet, writes []*types.TypeName, rewrites map[string]bool) Planner {
	p := Planner{
		fset:      fset,
		targets:   make(map[*types.TypeName]bool, len(writes)),
		rewritten: rewrites,
		marks:     make(map[mark]bool),
	}
	for _, obj := range writes {
		p.targets[obj] = true
	}
	return p
}

// Struct plans the checks of the fields of s, in declaration order, leaving out
// those with nothing to check, and says what is wrong with the rest: a rule
// that does not apply where it is written, or a tag nothing can run.
func (p Planner) Struct(s scan.Struct) ([]Field, []diag.Diag) {
	fields := make([]sibling, len(s.Fields))
	for i, f := range s.Fields {
		name, _ := JSONName(f)
		fields[i] = sibling{name: f.Name, jsonName: name, typ: f.Type}
	}

	own := s.Named.Obj().Pkg()
	imports := qualifier.Of(s.File, own)
	var (
		planned []Field
		diags   []diag.Diag
	)
	for i, f := range s.Fields {
		if f.Name == "_" {
			// Nothing can read a blank field, so nothing checks it.
			if _, tagged := f.Tag.Lookup(tagKey); tagged {
				diags = append(diags, diag.Errorf(f.Pos,
					"a field named _ cannot be read, so its validate tag would check nothing (field _)").
					WithHints("give the field a name"))
			}
			continue
		}
		if packages.Invalid(f.Type) {
			diags = append(diags, packages.NotTypeChecked(f.Pos))
			continue
		}
		if rest, ok := ruleAfterPattern(f.Tag); ok {
			diags = append(diags, diag.Warningf(f.Pos,
				"pattern= takes the rest of the tag as its regular expression, so %q is part of it (field %s)", rest, f.Name).
				WithHints("write pattern= last, after the other rules"))
		}
		at := site{
			pkg: own, imports: imports, fields: slices.Delete(slices.Clone(fields), i, i+1),
			self: f.Name, owner: s.Named,
		}
		v, errs := p.field(f, at)
		for _, err := range errs {
			diags = append(diags, fieldDiag(f, err))
		}
		if len(errs) == 0 && v != nil {
			planned = append(planned, Field{Field: f, Value: v})
		}
	}
	return planned, diags
}

func (p Planner) field(f scan.Field, at site) (*Value, []error) {
	levels, err := parseTag(f.Tag)
	if err != nil {
		return nil, []error{err}
	}
	return p.value(f.Type, levels, at, nil)
}

// value plans the checks of a value of type t, or returns nil when there is
// nothing to check. levels[0] holds the rules for the value itself and the
// rest those for its elements, one level per dive.
//
// enclosing are the types of the values this one was reached through without
// a dive: through a pointer, or looking for elements that validate themselves.
// A type among them contains itself, as type Tree map[string]Tree does, and is
// checked already.
func (p Planner) value(t types.Type, levels []level, at site, enclosing []types.Type) (*Value, []error) {
	if slices.ContainsFunc(enclosing, func(e types.Type) bool { return types.Identical(e, t) }) {
		return nil, nil
	}
	enclosing = append(slices.Clip(enclosing), t)

	var l level
	if len(levels) > 0 {
		l = levels[0]
	}
	var below []level
	if len(levels) > 1 {
		below = levels[1:]
	}

	if l.omitEmpty && skipsWhenNil(t) {
		return nil, []error{omitsNothing(t, at)}
	}
	v := &Value{typ: t, required: l.required, omitEmpty: l.omitEmpty}
	if l.required || l.omitEmpty {
		zero, ok := zeroTestOf(t)
		if !ok {
			return nil, []error{cannotTellEmpty(l, t, at)}
		}
		v.zero = zero
	}

	// A pointer is only ever nil or not; every rule but required and
	// omitempty is about what it points to.
	if ptr, ok := t.Underlying().(*types.Pointer); ok {
		pointee, errs := p.value(ptr.Elem(), append([]level{{rules: l.rules}}, below...), at, enclosing)
		v.pointee = pointee
		return pruned(v), errs
	}

	var (
		errs     []error
		resolved []rule
	)
	for _, r := range l.rules {
		c, err := resolve(r, t, at)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		v.checks = append(v.checks, c)
		resolved = append(resolved, r)
	}
	errs = append(errs, conflicts(resolved, v.checks)...)

	path, nest := p.findValidate(t)
	v.nest = nest
	if nest {
		var hidden *types.Var
		if v.nilable, hidden = nilableOn(path, at.pkg); hidden != nil {
			errs = append(errs, cannotTestNil(hidden, t, at))
		}
	}

	elem, ok := elemOf(t)
	elemAt := site{pkg: at.pkg, imports: at.imports}
	switch {
	case len(below) > 0 && !ok:
		errs = append(errs, ruleErrorf("dive needs a slice, array, or map, not %s", at.typeString(t)))
	case len(below) > 0:
		var es []error
		v.elem, es = p.value(elem, below, elemAt, nil)
		errs = append(errs, es...)
	case ok && !v.nest:
		// The elements are validated whether or not the tag dives: a slice of
		// structs that validate themselves is checked as the structs would be.
		var es []error
		v.elem, es = p.value(elem, nil, elemAt, enclosing)
		errs = append(errs, es...)
	}

	if l.omitEmpty && len(l.rules) == 0 {
		if err := omitsNothingElse(v, len(below) > 0, at); err != nil {
			errs = append(errs, err)
		}
	}
	return pruned(v), errs
}

// pruned returns v, or nil when it checks nothing.
func pruned(v *Value) *Value {
	if !v.required && len(v.checks) == 0 && !v.nest && v.pointee == nil && v.elem == nil {
		return nil
	}
	return v
}

// elemOf returns the element type of a slice or array, or the value type of a
// map.
func elemOf(t types.Type) (types.Type, bool) {
	switch u := t.Underlying().(type) {
	case *types.Slice:
		return u.Elem(), true
	case *types.Array:
		return u.Elem(), true
	case *types.Map:
		return u.Elem(), true
	}
	return nil, false
}

// zeroTestOf returns how generated code tells the zero value of t, and false
// when it cannot.
func zeroTestOf(t types.Type) (zeroTest, bool) {
	// A nil pointer or interface cannot have IsZero called on it, so these are
	// compared with nil even when what they hold has the method.
	switch t.Underlying().(type) {
	case *types.Pointer, *types.Interface, *types.Slice, *types.Map, *types.Chan, *types.Signature:
		return zeroNil, true
	}
	if hasIsZero(t) {
		return zeroMethod, true
	}

	if b, ok := t.Underlying().(*types.Basic); ok {
		switch info := b.Info(); {
		case info&types.IsString != 0:
			return zeroString, true
		case info&types.IsNumeric != 0:
			return zeroNumber, true
		case info&types.IsBoolean != 0:
			return zeroBool, true
		}
	}
	if types.Comparable(t) {
		return zeroComposite, true
	}
	return 0, false
}

// hasIsZero reports whether t, or a pointer to it, has an IsZero() bool method.
// The generated code calls it on an addressable value, so either receiver works.
func hasIsZero(t types.Type) bool {
	obj, _, _ := types.LookupFieldOrMethod(t, true, nil, "IsZero")
	fn, ok := obj.(*types.Func)
	if !ok {
		return false
	}
	sig := fn.Signature()
	return sig.Params().Len() == 0 && sig.Results().Len() == 1 &&
		types.Identical(sig.Results().At(0).Type(), types.Typ[types.Bool])
}

// skipsWhenNil reports whether a nil value of t skips every rule but required,
// as a pointer and an interface do, so that omitempty adds nothing.
func skipsWhenNil(t types.Type) bool {
	switch t.Underlying().(type) {
	case *types.Pointer, *types.Interface:
		return true
	}
	return false
}

// omitsNothing reports omitempty on t, a pointer or an interface, where it does
// nothing.
func omitsNothing(t types.Type, at site) *ruleError {
	kind := "pointer"
	if types.IsInterface(t) {
		kind = "interface"
	}
	err := ruleErrorf("omitempty does nothing on %s: a nil %s skips every rule but required already",
		at.typeString(t), kind)
	err.hint = "remove omitempty"
	return err
}

// omitsNothingElse reports omitempty on v, a value with no rule after it at its
// level, when it skips nothing for the zero value: neither Validate, nor the
// elements of an array, as a nil slice or map has none to check anyway. dives
// says rules after a dive check the elements.
func omitsNothingElse(v *Value, dives bool, at site) *ruleError {
	if v.nest {
		return nil
	}
	if dives || v.elem != nil {
		if shapeOf(v.typ) == shapeArray {
			return nil
		}
		err := ruleErrorf("omitempty does nothing on %s without a rule of its own: an empty one has no elements to check",
			at.typeString(v.typ))
		err.hint = "remove omitempty"
		return err
	}
	err := ruleErrorf("omitempty does nothing without a rule after it: nothing checks %s", at.typeString(v.typ))
	err.hint = "remove omitempty, or write after it the rules the zero value is to skip"
	return err
}

// cannotTellEmpty reports required or omitempty, written in l, on a type whose
// zero value generated code cannot tell.
func cannotTellEmpty(l level, t types.Type, at site) *ruleError {
	name := "omitempty"
	if l.required {
		name = "required"
	}
	err := ruleErrorf("%s cannot tell whether %s is empty", name, at.typeString(t))
	err.hint = "it is not comparable and has no IsZero() bool method; give it one, or use a pointer"
	return err
}

// findValidate reports whether the generated code can call Validate() error on
// a value of type t, once the generators have run, and returns the embedded
// fields it is promoted through, outermost first.
//
// A struct of another package marked //kanna:validate has it once that
// package's own run writes it, which go generate ./... may run after this one,
// so the mark decides, and an earlier run's output counts only for what is
// marked still. An enum has it once kanna-value writes it, which may be after
// this run too, and the same goes for what kanna-value wrote earlier.
//
// A type has it through what it embeds as well, which go/types can tell only of
// what is written. So the method is looked for as the compiler looks for it,
// level by level of embedding: the first level to name it decides, and two
// names there collide, which leaves the type without it.
func (p Planner) findValidate(t types.Type) ([]*types.Var, bool) {
	seen := make(map[types.Type]bool)
	for level := []embedding{{typ: types.Unalias(t)}}; len(level) > 0; {
		for _, e := range level {
			seen[origin(e.typ)] = true
		}

		var (
			found    []embedding // what names Validate at this level
			callable bool
			next     []embedding
		)
		for _, e := range level {
			if named, ok := p.ownValidate(e.typ); named {
				found, callable = append(found, e), ok
				continue
			}
			for _, inner := range e.embedded() {
				if !seen[origin(inner.typ)] {
					next = append(next, inner)
				}
			}
		}
		if len(found) > 0 {
			if len(found) > 1 || !callable {
				return nil, false
			}
			return found[0].path, true
		}
		level = next
	}
	return nil, false
}

// ownValidate reports whether t, leaving aside what it embeds, names Validate
// once the generators have run, and whether that is a Validate() error.
func (p Planner) ownValidate(t types.Type) (named, callable bool) {
	if n, ok := t.(*types.Named); ok {
		if obj := n.Obj(); p.targets[obj] || p.elsewhere(obj) && p.marked(obj, DirectiveKey) || p.valueWritesValidate(n) {
			return true, true
		}
		for m := range n.Methods() {
			if m.Name() == "Validate" && !p.leftover(m) {
				return true, isValidate(m.Signature())
			}
		}
	}

	switch u := t.Underlying().(type) {
	case *types.Struct:
		for f := range u.Fields() {
			if f.Name() == "Validate" {
				return true, false
			}
		}
	case *types.Interface:
		for m := range u.Methods() {
			if m.Name() == "Validate" {
				return true, isValidate(m.Signature())
			}
		}
	}
	return false, false
}

// leftover reports whether fn, on a type no generator gives Validate, is what
// an earlier run generated: the next run of that generator takes it away.
func (p Planner) leftover(fn *types.Func) bool {
	path := p.fset.Position(fn.Pos()).Filename
	return writtenBy(path, OutputFile, Generator) || writtenBy(path, valueOutputFile, valueGenerator)
}

// isValidate reports whether sig is that of Validate() error.
func isValidate(sig *types.Signature) bool {
	return sig.Params().Len() == 0 && sig.Results().Len() == 1 &&
		types.Identical(sig.Results().At(0).Type(), types.Universe.Lookup("error").Type())
}

// origin returns the generic type t is an instance of, whose names it shares,
// or else t.
func origin(t types.Type) types.Type {
	if n, ok := t.(*types.Named); ok {
		return n.Origin()
	}
	return t
}

// embedding is a type reached through what another embeds.
type embedding struct {
	typ types.Type

	// path holds the embedded fields leading to it, outermost first.
	path []*types.Var
}

// embedded returns what e embeds, if it is a struct, without the pointers it
// may be embedded by.
func (e embedding) embedded() []embedding {
	s, ok := e.typ.Underlying().(*types.Struct)
	if !ok {
		return nil
	}
	var inner []embedding
	for f := range s.Fields() {
		if !f.Embedded() {
			continue
		}
		typ := types.Unalias(f.Type())
		if ptr, isPtr := typ.(*types.Pointer); isPtr {
			typ = types.Unalias(ptr.Elem())
		}
		inner = append(inner, embedding{typ: typ, path: append(slices.Clip(e.path), f)})
	}
	return inner
}

// nilableOn returns the selectors of the fields on path that may be nil, each
// from the start of path, for code of pkg to test. A field another package does
// not export leaves what is on its way out of reach of pkg, and is returned
// when something there needs testing.
func nilableOn(path []*types.Var, pkg *types.Package) (selectors []string, hidden *types.Var) {
	var (
		selector string
		blocked  *types.Var
	)
	for _, f := range path {
		selector = strings.TrimPrefix(selector+"."+f.Name(), ".")
		if blocked == nil && !f.Exported() && f.Pkg().Path() != pkg.Path() {
			blocked = f
		}
		if _, isPtr := types.Unalias(f.Type()).(*types.Pointer); !isPtr && !types.IsInterface(f.Type()) {
			continue
		}
		if blocked != nil {
			return nil, blocked
		}
		selectors = append(selectors, selector)
	}
	return selectors, nil
}

// cannotTestNil reports a Validate of t promoted through what may be nil, which
// the struct's package cannot test as field is not exported. Calling it might
// panic, and leaving it out would let any value through.
func cannotTestNil(field *types.Var, t types.Type, at site) *ruleError {
	err := ruleErrorf("%s has Validate through an embedded field that may be nil, which package %s cannot test, "+
		"as %s is not exported", at.typeString(t), at.pkg.Name(), field.Name())
	err.hint = "give " + at.typeString(t) + " a Validate of its own, or export " + field.Name()
	return err
}

// writtenBy reports whether tool wrote the file at path, which it names name.
// The name does not tell alone, as anyone may give a file that name.
func writtenBy(path, name, tool string) bool {
	if filepath.Base(path) != name {
		return false
	}
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.PackageClauseOnly|parser.ParseComments)
	if err != nil || !ast.IsGenerated(f) {
		return false
	}
	for _, group := range f.Comments {
		for _, c := range group.List {
			if m := generatedHeader.FindStringSubmatch(c.Text); m != nil && m[1] == tool {
				return true
			}
		}
	}
	return false
}

// valueWritesValidate reports whether kanna-value writes the Validate of
// named, which it does for a string type marked //kanna:enum, and which may
// not be written yet. It is no test of what an enum is, which rule= and oneof
// take from enumtype, as every generator does: the mark tells what kanna-value
// is to write, and constants, which export data may leave out, do not.
func (p Planner) valueWritesValidate(named *types.Named) bool {
	return named.TypeParams().Len() == 0 && types.Identical(named.Underlying(), types.Typ[types.String]) &&
		p.marked(named.Obj(), enumKey)
}

// elsewhere reports whether obj is declared in a package this run does not
// rewrite.
func (p Planner) elsewhere(obj *types.TypeName) bool {
	return obj.Pkg() != nil && !p.rewritten[obj.Pkg().Path()]
}

// marked reports whether the declaration of obj carries //kanna:<key>, reading
// the file it is in: a package loaded from export data has no syntax.
func (p Planner) marked(obj *types.TypeName, key string) bool {
	if marked, ok := p.marks[mark{obj, key}]; ok {
		return marked
	}
	marked := false
	if path := p.fset.Position(obj.Pos()).Filename; path != "" {
		fset := token.NewFileSet()
		if f, err := parser.ParseFile(fset, path, nil, parser.ParseComments|parser.SkipObjectResolution); err == nil {
			marked = declMarked(fset, f, obj.Name(), key)
		}
	}
	p.marks[mark{obj, key}] = marked
	return marked
}

// declMarked reports whether f declares the type name with //kanna:<key>.
func declMarked(fset *token.FileSet, f *ast.File, name, key string) bool {
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			if ts, ok := spec.(*ast.TypeSpec); ok && ts.Name.Name == name {
				doc := ts.Doc
				if doc == nil && len(gd.Specs) == 1 {
					doc = gd.Doc
				}
				d, _ := directive.Find(fset, doc, key)
				return d.Found
			}
		}
	}
	return false
}

// JSONName returns the name encoding/json gives f, and whether its json tag
// names it; without a name there, it is the Go name.
func JSONName(f scan.Field) (string, bool) {
	tag, ok := f.Tag.Lookup("json")
	if !ok || tag == "-" {
		return f.Name, false
	}
	if name, _, _ := strings.Cut(tag, ","); name != "" {
		return name, true
	}
	return f.Name, false
}

// fieldDiag reports err at f, naming the field after the problem, as in
// `unknown rule "maxx" (field Name)`.
func fieldDiag(f scan.Field, err error) diag.Diag {
	d := diag.Errorf(f.Pos, "%v (field %s)", err, f.Name)
	if e, ok := errors.AsType[*ruleError](err); ok && e.hint != "" {
		d = d.WithHints(e.hint)
	}
	return d
}
