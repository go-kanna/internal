const generated = "// Code generated by kanna-test. DO NOT EDIT.\n\npackage p\n"

type config struct {
	tags string
}

type runFunc = func(dir string, cfg config, args []string) ([]output.Change, []diag.Diag)

func command(run runFunc) cli.Command[config] {
	return cli.Command[config]{
		Name:    "kanna-test",
		Summary: "generate what tests need",
		Args:    "[packages]",
		Help:    "The packages default to the one in the current directory.",
		Flags: func(fs *flag.FlagSet, cfg *config) {
			fs.StringVar(&cfg.tags, "tags", "", "comma-separated build tags")
		},
		Run: run,
	}
}

// generates returns a Run that generates p_gen.go into its directory, along
// with ds.
func generates(ds ...diag.Diag) runFunc {
	return func(dir string, _ config, _ []string) ([]output.Change, []diag.Diag) {
		return []output.Change{{Path: filepath.Join(dir, "p_gen.go"), Data: []byte(generated)}}, ds
	}
}

type result struct {
	code        int
	stdout, err string
}

func execute(t *testing.T, cmd cli.Command[config], dir string, args ...string) result {
	t.Helper()

	return executeIn(t, cmd, cli.Env{Dir: dir}, args...)
}

// executeIn runs cmd in env, with Out and Err replaced to capture them.
func executeIn(t *testing.T, cmd cli.Command[config], env cli.Env, args ...string) result {
	t.Helper()

	var stdout, stderr strings.Builder
	env.Out, env.Err = &stdout, &stderr
	code := cmd.Exec(env, args)
	return result{code: code, stdout: stdout.String(), err: stderr.String()}
}

func contents(t *testing.T, path string) string {
	t.Helper()

	data, err := os.ReadFile(filepath.Clean(path))
	if err != nil && !os.IsNotExist(err) {
		t.Fatal(err)
	}
	return string(data)
}

func local(name string) string {
	return "." + string(filepath.Separator) + name
}

func TestExec_WritesWithoutAWord(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	got := execute(t, command(generates()), dir)

	if got != (result{code: cli.ExitOK}) {
		t.Errorf("Exec() = %+v, want success and no output", got)
	}
	if c := contents(t, filepath.Join(dir, "p_gen.go")); c != generated {
		t.Errorf("p_gen.go holds %q, want %q", c, generated)
	}
}

func TestExec_Verbose(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	cmd := command(generates())

	for _, want := range []string{"wrote " + local("p_gen.go") + "\n", "unchanged " + local("p_gen.go") + "\n"} {
		if got := execute(t, cmd, dir, "-v"); got != (result{code: cli.ExitOK, stdout: want}) {
			t.Errorf("Exec(-v) = %+v, want stdout %q", got, want)
		}
	}
}

func TestExec_Check(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		existing string // "" for no file
		want     result
	}{
		{name: "up to date", existing: generated, want: result{code: cli.ExitOK}},
		{
			name:     "out of date",
			existing: "// Code generated by kanna-test. DO NOT EDIT.\n\npackage old\n",
			want:     result{code: cli.ExitFailure, err: local("p_gen.go") + ": error: out of date; run go generate\n"},
		},
		{
			name: "not generated yet",
			want: result{code: cli.ExitFailure, err: local("p_gen.go") + ": error: not generated yet; run go generate\n"},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			path := filepath.Join(dir, "p_gen.go")
			if tt.existing != "" {
				if err := os.WriteFile(path, []byte(tt.existing), 0o600); err != nil {
					t.Fatal(err)
				}
			}

			if got := execute(t, command(generates()), dir, "-check"); got != tt.want {
				t.Errorf("Exec(-check) = %+v, want %+v", got, tt.want)
			}
			if c := contents(t, path); c != tt.existing {
				t.Errorf("-check changed p_gen.go to %q", c)
			}
		})
	}
}

// KANNA_CHECK turns on -check, so that go generate can check every generator
// without the flags of a //go:generate line changing.
func TestExec_CheckFromEnvironment(t *testing.T) {
	t.Parallel()

	const old = "// Code generated by kanna-test. DO NOT EDIT.\n\npackage old\n"
	outOfDate := result{code: cli.ExitFailure, err: local("p_gen.go") + ": error: out of date; run go generate\n"}

	tests := []struct {
		name     string
		value    string
		args     []string
		want     result
		wantFile string
	}{
		{name: "1", value: "1", want: outOfDate, wantFile: old},
		{name: "true", value: "true", want: outOfDate, wantFile: old},
		{name: "0", value: "0", want: result{code: cli.ExitOK}, wantFile: generated},
		{name: "unset", value: "", want: result{code: cli.ExitOK}, wantFile: generated},
		// It only ever turns -check on.
		{name: "0 with -check", value: "0", args: []string{"-check"}, want: outOfDate, wantFile: old},
		{
			name:     "not a boolean",
			value:    "yes",
			want:     result{code: cli.ExitUsage, err: "kanna-test: KANNA_CHECK=\"yes\" is not a boolean such as 1 or true\n"},
			wantFile: old,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			path := filepath.Join(dir, "p_gen.go")
			if err := os.WriteFile(path, []byte(old), 0o600); err != nil {
				t.Fatal(err)
			}
			getenv := func(key string) string {
				if key == "KANNA_CHECK" {
					return tt.value
				}
				return ""
			}

			if got := executeIn(t, command(generates()), cli.Env{Dir: dir, Getenv: getenv}, tt.args...); got != tt.want {
				t.Errorf("Exec(%q) with KANNA_CHECK=%q = %+v, want %+v", tt.args, tt.value, got, tt.want)
			}
			if c := contents(t, path); c != tt.wantFile {
				t.Errorf("p_gen.go holds %q, want %q", c, tt.wantFile)
			}
		})
	}
}

func TestExec_Diagnostics(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name      string
		severity  func(token.Position, string, ...any) diag.Diag
		want      int
		wantWrite bool
	}{
		// An error stops the run before anything is written.
		{name: "error", severity: diag.Errorf, want: cli.ExitFailure, wantWrite: false},
		{name: "warning", severity: diag.Warningf, want: cli.ExitOK, wantWrite: true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			d := tt.severity(token.Position{Filename: filepath.Join(dir, "p.go"), Line: 3, Column: 1}, "problem")

			got := execute(t, command(generates(d)), dir)
			if want := local("p.go") + ":3:1: " + tt.name + ": problem\n"; got.code != tt.want || got.err != want {
				t.Errorf("Exec() = %+v, want code %d and stderr %q", got, tt.want, want)
			}
			if written := contents(t, filepath.Join(dir, "p_gen.go")) != ""; written != tt.wantWrite {
				t.Errorf("p_gen.go written: %v, want %v", written, tt.wantWrite)
			}
		})
	}
}

func TestExec_ApplyFailure(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "p_gen.go"), []byte("package p\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	got := execute(t, command(generates()), dir)
	if got.code != cli.ExitFailure || !strings.HasPrefix(got.err, local("p_gen.go")+": error: ") {
		t.Errorf("Exec() over a hand-written file = %+v, want an error about it", got)
	}
}

func TestExec_PassesFlagsAndArguments(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	type call struct {
		dir  string
		cfg  config
		args []string
	}
	var calls []call
	cmd := command(func(dir string, cfg config, args []string) ([]output.Change, []diag.Diag) {
		calls = append(calls, call{dir: dir, cfg: cfg, args: args})
		return nil, nil
	})

	execute(t, cmd, dir, "-tags", "a,b", "./model", "help")
	// Every run starts from a zero config.
	execute(t, cmd, dir)

	if len(calls) != 2 {
		t.Fatalf("Run called %d times, want 2", len(calls))
	}
	// A "help" that does not lead is an argument like any other.
	if got := calls[0]; got.dir != dir || got.cfg.tags != "a,b" || !slices.Equal(got.args, []string{"./model", "help"}) {
		t.Errorf("first run = %+v", got)
	}
	if got := calls[1]; got.cfg.tags != "" || len(got.args) != 0 {
		t.Errorf("second run = %+v, want a zero config and no arguments", got)
	}
}

func TestExec_WorkingDirectory(t *testing.T) {
	t.Parallel()

	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	var got string
	execute(t, command(func(dir string, _ config, _ []string) ([]output.Change, []diag.Diag) {
		got = dir
		return nil, nil
	}), "")

	if got != wd {
		t.Errorf("Run got dir %q, want the working directory %q", got, wd)
	}
}

func TestExec_UsageAndVersion(t *testing.T) {
	t.Parallel()

	usage := "kanna-test: generate what tests need\n\nUsage:\n  kanna-test [flags] [packages]\n\n" +
		"The packages default to the one in the current directory.\n\nFlags:\n"

	tests := []struct {
		name    string
		args    []string
		want    int
		wantOut string // a prefix of stdout
		wantErr string // a prefix of stderr
	}{
		{name: "help", args: []string{"help"}, want: cli.ExitOK, wantOut: usage},
		{name: "-h", args: []string{"-h"}, want: cli.ExitOK, wantOut: usage},
		{
			name:    "unknown flag",
			args:    []string{"-nope"},
			want:    cli.ExitUsage,
			wantErr: "flag provided but not defined: -nope\n" + usage,
		},
		{name: "-version", args: []string{"-version"}, want: cli.ExitOK, wantOut: "kanna-test "},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			ran := false
			got := execute(t, command(func(string, config, []string) ([]output.Change, []diag.Diag) {
				ran = true
				return nil, nil
			}), t.TempDir(), tt.args...)

			if got.code != tt.want || !strings.HasPrefix(got.stdout, tt.wantOut) || !strings.HasPrefix(got.err, tt.wantErr) {
				t.Errorf("Exec(%q) = %+v, want code %d, stdout %q..., stderr %q...",
					tt.args, got, tt.want, tt.wantOut, tt.wantErr)
			}
			if (tt.wantOut == "") != (got.stdout == "") || (tt.wantErr == "") != (got.err == "") {
				t.Errorf("Exec(%q) wrote to the wrong stream: %+v", tt.args, got)
			}
			if ran {
				t.Errorf("Exec(%q) ran the generator", tt.args)
			}
		})
	}

	// The flags are listed as the flag package lists them, the command's own
	// among them.
	if got := execute(t, command(generates()), t.TempDir(), "-h"); !strings.Contains(got.stdout, "  -tags string\n") ||
		!strings.Contains(got.stdout, "  -check\n") || !strings.Contains(got.stdout, "KANNA_CHECK=1") {
		t.Errorf("usage lists no -tags, or no -check with KANNA_CHECK:\n%s", got.stdout)
	}
}

// A command that takes no arguments refuses one, rather than leave Run to
// ignore it.
func TestExec_NoArguments(t *testing.T) {
	t.Parallel()

	ran := false
	cmd := command(func(string, config, []string) ([]output.Change, []diag.Diag) {
		ran = true
		return nil, nil
	})
	cmd.Args, cmd.Help = "", ""

	got := execute(t, cmd, t.TempDir(), "-tags", "a", "extra")
	wantErr := "unexpected argument \"extra\"\n" +
		"kanna-test: generate what tests need\n\nUsage:\n  kanna-test [flags]\n\nFlags:\n"
	if got.code != cli.ExitUsage || !strings.HasPrefix(got.err, wantErr) || got.stdout != "" {
		t.Errorf("Exec() = %+v, want code %d and stderr %q...", got, cli.ExitUsage, wantErr)
	}
	if ran {
		t.Error("Exec() ran the generator")
	}

	if got := execute(t, cmd, t.TempDir(), "-tags", "a"); got.code != cli.ExitOK || !ran {
		t.Errorf("Exec() without arguments = %+v, ran = %v, want code %d and a run", got, ran, cli.ExitOK)
	}
}
