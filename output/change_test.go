const (
	generated  = "// Code generated by kanna-test. DO NOT EDIT.\n\npackage p\n"
	regenerate = "// Code generated by kanna-test. DO NOT EDIT.\n\npackage p\n\nvar V = 1\n"
	// The marker counts below a license header, as Go defines it.
	licensed    = "// Copyright 2026 Someone.\n\n// Code generated by kanna-test. DO NOT EDIT.\n\npackage p\n"
	released    = "// Code generated by kanna-test v0.0.1. DO NOT EDIT.\n\npackage p\n"
	handwritten = "package p\n"
	// A merge of two branches that regenerated with different releases.
	conflicted = "<<<<<<< HEAD\n// Code generated by kanna-test v0.0.1. DO NOT EDIT.\n=======\n" +
		"// Code generated by kanna-test v0.0.2. DO NOT EDIT.\n>>>>>>> feature\n\npackage p\n"
	// The markers are no header.
	conflictedHandWritten = "<<<<<<< HEAD\n=======\n>>>>>>> feature\n\npackage p\n"
)

// put writes each of files into dir and returns the path of the one named
// "p_gen.go".
func put(t *testing.T, dir string, files map[string]string) string {
	t.Helper()

	for name, src := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return filepath.Join(dir, "p_gen.go")
}

func read(t *testing.T, path string) (string, bool) {
	t.Helper()

	data, err := os.ReadFile(filepath.Clean(path))
	if errors.Is(err, fs.ErrNotExist) {
		return "", false
	}
	if err != nil {
		t.Fatal(err)
	}
	return string(data), true
}

func messages(ds []diag.Diag) []string {
	out := make([]string, 0, len(ds))
	for _, d := range ds {
		out = append(out, d.Message)
	}
	return out
}

const handWrittenMsg = "has no generated-code header, so it looks hand-written; go generate leaves it alone"

func TestCheck(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		existing string // "" for no file
		data     string // what the run generates; regenerate when empty
		remove   bool
		want     []string
	}{
		{name: "up to date", existing: regenerate},
		{name: "up to date below a license header", existing: licensed, data: licensed},
		{name: "not generated yet", want: []string{"not generated yet; run go generate"}},
		{name: "out of date", existing: generated, want: []string{"out of date; run go generate"}},
		{name: "hand-written", existing: handwritten, want: []string{handWrittenMsg}},
		{name: "a conflict", existing: conflicted, want: []string{"out of date; run go generate"}},
		{name: "a conflict in a hand-written file", existing: conflictedHandWritten, want: []string{handWrittenMsg}},
		{
			name:     "left over",
			existing: generated,
			remove:   true,
			want:     []string{"left over from an earlier run; run go generate"},
		},
		{name: "already removed", remove: true},
		{name: "hand-written where a removal is due", existing: handwritten, remove: true, want: []string{handWrittenMsg}},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			path := filepath.Join(dir, "p_gen.go")
			if tt.existing != "" {
				put(t, dir, map[string]string{"p_gen.go": tt.existing})
			}
			data := cmp.Or(tt.data, regenerate)

			ds := output.Check([]output.Change{{Path: path, Data: []byte(data), Remove: tt.remove}})
			if got := messages(ds); !slices.Equal(got, tt.want) {
				t.Errorf("Check() = %q, want %q", got, tt.want)
			}
			for _, d := range ds {
				if d.Pos.Filename != path {
					t.Errorf("diagnostic at %q, want %q", d.Pos.Filename, path)
				}
			}
		})
	}
}

func TestCheck_ReportsEveryFile(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	put(t, dir, map[string]string{"a_gen.go": generated, "b_gen.go": generated})

	ds := output.Check([]output.Change{
		{Path: filepath.Join(dir, "a_gen.go"), Data: []byte(regenerate)},
		{Path: filepath.Join(dir, "b_gen.go"), Data: []byte(regenerate)},
	})
	if len(ds) != 2 {
		t.Errorf("Check() = %v, want a diagnostic for each file", ds)
	}
}

func TestCheck_Unreadable(t *testing.T) {
	t.Parallel()

	// A directory where the file should be cannot be read as one.
	dir := t.TempDir()
	path := filepath.Join(dir, "p_gen.go")
	if err := os.Mkdir(path, 0o750); err != nil {
		t.Fatal(err)
	}

	ds := output.Check([]output.Change{{Path: path, Data: []byte(regenerate)}})
	if len(ds) != 1 || !diag.HasErrors(ds) {
		t.Fatalf("Check() = %v, want one error", ds)
	}
	// The diagnostic is positioned at the path; the message need not repeat it.
	if msg := ds[0].Message; msg == "" || strings.Contains(msg, path) {
		t.Errorf("Message = %q, want the failure without the path", msg)
	}
}

func TestApply(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name       string
		existing   string // "" for no file
		remove     bool
		want       output.Action
		wantResult string // what the file holds afterwards; "" when it is gone
	}{
		{name: "new file", want: output.Wrote, wantResult: regenerate},
		{name: "unchanged", existing: regenerate, want: output.Unchanged, wantResult: regenerate},
		{name: "regenerated", existing: generated, want: output.Wrote, wantResult: regenerate},
		{name: "regenerated below a license header", existing: licensed, want: output.Wrote, wantResult: regenerate},
		{name: "regenerated over a release's output", existing: released, want: output.Wrote, wantResult: regenerate},
		{name: "regenerated over a conflict", existing: conflicted, want: output.Wrote, wantResult: regenerate},
		{name: "removed", existing: generated, remove: true, want: output.Removed},
		{name: "already removed", remove: true, want: output.Unchanged},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := t.TempDir()
			path := filepath.Join(dir, "p_gen.go")
			if tt.existing != "" {
				put(t, dir, map[string]string{"p_gen.go": tt.existing})
			}

			done, ds := output.Apply([]output.Change{{Path: path, Data: []byte(regenerate), Remove: tt.remove}})
			if len(ds) > 0 {
				t.Fatalf("Apply() diagnostics = %v", ds)
			}
			if want := []output.Applied{{Path: path, Action: tt.want}}; !slices.Equal(done, want) {
				t.Errorf("Apply() = %v, want %v", done, want)
			}
			got, ok := read(t, path)
			if ok != (tt.wantResult != "") || got != tt.wantResult {
				t.Errorf("file holds %q (exists %v), want %q", got, ok, tt.wantResult)
			}
		})
	}
}

func TestApply_CreatesTheDirectory(t *testing.T) {
	t.Parallel()

	path := filepath.Join(t.TempDir(), "fixture", "p_gen.go")

	if _, ds := output.Apply([]output.Change{{Path: path, Data: []byte(regenerate)}}); len(ds) > 0 {
		t.Fatalf("Apply() diagnostics = %v", ds)
	}
	if got, _ := read(t, path); got != regenerate {
		t.Errorf("file holds %q, want %q", got, regenerate)
	}
}

func TestApply_LeavesHandWrittenFilesAlone(t *testing.T) {
	t.Parallel()

	for _, remove := range []bool{false, true} {
		dir := t.TempDir()
		hand := put(t, dir, map[string]string{"p_gen.go": handwritten})
		next := filepath.Join(dir, "next_gen.go")

		done, ds := output.Apply([]output.Change{
			{Path: hand, Data: []byte(regenerate), Remove: remove},
			{Path: next, Data: []byte(regenerate)},
		})

		if got := messages(ds); !slices.Equal(got, []string{handWrittenMsg}) {
			t.Errorf("remove=%v: Apply() = %q, want the hand-written refusal", remove, got)
		}
		if got, _ := read(t, hand); got != handwritten {
			t.Errorf("remove=%v: hand-written file now holds %q", remove, got)
		}
		// Apply stops at the first failure.
		if _, ok := read(t, next); ok || len(done) > 0 {
			t.Errorf("remove=%v: Apply() went on past the failure: %v", remove, done)
		}
	}
}

func TestApply_ReportsFailures(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	put(t, dir, map[string]string{"file": handwritten})
	if err := os.Mkdir(filepath.Join(dir, "p_gen.go"), 0o750); err != nil {
		t.Fatal(err)
	}
	locked := filepath.Join(dir, "locked")
	if err := os.Mkdir(locked, 0o500); err != nil {
		t.Fatal(err)
	}

	tests := []struct {
		name       string
		path       string
		permission bool // fails only for a user that permissions bind
	}{
		// A directory where the file should be cannot be read as one.
		{name: "unreadable", path: filepath.Join(dir, "p_gen.go")},
		// Nor can a path through a file.
		{name: "a file where a directory should be", path: filepath.Join(dir, "file", "p_gen.go")},
		{name: "a directory that cannot be created", path: filepath.Join(locked, "fixture", "p_gen.go"), permission: true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			if tt.permission && os.Geteuid() == 0 {
				t.Skip("root is not bound by directory permissions")
			}

			_, ds := output.Apply([]output.Change{{Path: tt.path, Data: []byte(regenerate)}})
			if len(ds) != 1 || ds[0].Pos.Filename != tt.path {
				t.Fatalf("Apply() = %v, want one error at %s", ds, tt.path)
			}
			if strings.Contains(ds[0].Message, tt.path) {
				t.Errorf("Message = %q repeats the path", ds[0].Message)
			}
		})
	}
}

