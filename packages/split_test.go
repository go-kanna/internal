package packages_test

import (
	"slices"
	"testing"

	"github.com/go-kanna/internal/diag"
	"github.com/go-kanna/internal/packages"
)

func TestSet_Split(t *testing.T) {
	t.Parallel()

	const undefined = "var _ = F()\n" // a type error at 3:9

	tests := []struct {
		name         string
		files        map[string]string
		pattern      string
		tests        bool
		wantBlocking []string
		wantDeferred []string
	}{
		{
			name:         "a type error of a root",
			files:        map[string]string{"p/p.go": "package p\n\n" + undefined},
			pattern:      "./p",
			wantDeferred: []string{"p/p.go:3:9"},
		},
		{
			name: "a type error of a root that does not parse",
			files: map[string]string{
				"p/p.go": "package p\n\n" + undefined,
				"p/q.go": "package p\n\nfunc G( {\n",
			},
			pattern:      "./p",
			wantBlocking: []string{"p/p.go:3:9", "p/q.go:3:9"},
		},
		{
			name: "roots that do and do not parse",
			files: map[string]string{
				"p/p.go": "package p\n\n" + undefined,
				"q/q.go": "package q\n\nfunc G( {\n",
			},
			pattern:      "./...",
			wantBlocking: []string{"q/q.go:3:9"},
			wantDeferred: []string{"p/p.go:3:9"},
		},
		{
			name: "a type error of a dependency",
			files: map[string]string{
				"a/a.go": "package a\n\nimport \"example.com/m/b\"\n\nvar _ = b.V\n",
				"b/b.go": "package b\n\nvar V int\n\n" + undefined,
			},
			pattern:      "./a",
			wantBlocking: []string{"b/b.go:5:9"},
		},
		{
			// b imports a as itself, the test variant is the root.
			name: "a tested package another root imports",
			files: map[string]string{
				"a/a.go":      "package a\n\nvar V int\n\n" + undefined,
				"a/a_test.go": "package a\n\n" + undefined,
				"a/x_test.go": "package a_test\n\n" + undefined,
				"b/b.go":      "package b\n\nimport \"example.com/m/a\"\n\nvar _ = a.V\n",
			},
			pattern:      "./...",
			tests:        true,
			wantDeferred: []string{"a/a.go:5:9", "a/a_test.go:3:9", "a/x_test.go:3:9"},
		},
		{
			name:         "no such directory",
			files:        map[string]string{},
			pattern:      "./nothing",
			wantBlocking: []string{"-"},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := module(t, tt.files)
			set := load(t, []string{tt.pattern}, packages.Config{Dir: dir, Tests: tt.tests})
			blocking, deferred := set.Split()

			if got := where(t, dir, blocking); !slices.Equal(got, tt.wantBlocking) {
				t.Errorf("blocking at %q, want %q\n%v", got, tt.wantBlocking, blocking)
			}
			if got := where(t, dir, deferred); !slices.Equal(got, tt.wantDeferred) {
				t.Errorf("deferred at %q, want %q\n%v", got, tt.wantDeferred, deferred)
			}
		})
	}
}

func TestSet_SetAsideWarnings(t *testing.T) {
	t.Parallel()

	dir := module(t, map[string]string{
		"p/p.go": "package p\n\ntype T struct{}\n",
		"p/validate_gen.go": "// Code generated by kanna-validate. DO NOT EDIT.\n\n" +
			"package p\n\nfunc (T) Check(Missing) {}\n",
	})
	set := load(t, []string{"./p"}, packages.Config{Dir: dir, Regenerated: []string{"validate_gen.go"}})

	got := set.SetAsideWarnings()
	if w := where(t, dir, got); !slices.Equal(w, []string{"p/validate_gen.go:0:0"}) {
		t.Errorf("SetAsideWarnings() at %q, want p/validate_gen.go", w)
	}
	if diag.HasErrors(got) {
		t.Errorf("SetAsideWarnings() = %v, want warnings only", got)
	}
}
