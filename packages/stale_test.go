// relative lists paths relative to dir, sorted and without repeats.
func relative(t *testing.T, dir string, paths []string) []string {
	t.Helper()

	out := make([]string, 0, len(paths))
	for _, p := range paths {
		rel, err := filepath.Rel(dir, p)
		if err != nil {
			t.Fatal(err)
		}
		out = append(out, filepath.ToSlash(rel))
	}
	slices.Sort(out)
	return slices.Compact(out)
}

// errorFiles lists the files ds point into.
func errorFiles(ds []diag.Diag) []string {
	var files []string
	for _, d := range ds {
		if d.Pos.Filename != "" {
			files = append(files, d.Pos.Filename)
		}
	}
	return files
}

func TestLoad_SetsAsideStaleRegeneratedFiles(t *testing.T) {
	t.Parallel()

	const header = "// Code generated by kanna-validate. DO NOT EDIT.\n\n"

	tests := []struct {
		name         string
		files        map[string]string
		tests        bool
		wantErrorsIn []string
		wantSetAside []string
	}{
		{
			// The import that only the body used must not fail the stub either.
			name: "bodies that refer to what is gone",
			files: map[string]string{
				"p/p.go": "package p\n\ntype T struct{ A int }\n\nfunc Use(t T) error { return t.Validate() }\n",
				"p/validate_gen.go": header + "package p\n\nimport \"strings\"\n\n" +
					"func (t T) Validate() error {\n\t// B is gone from T.\n\t_ = strings.TrimSpace(t.B)\n\treturn nil\n}\n",
			},
		},
		{
			name: "declarations that refer to what is gone",
			files: map[string]string{
				"p/p.go":            "package p\n\ntype T struct{}\n",
				"p/validate_gen.go": header + "package p\n\nfunc (T) Check(Missing) {}\n",
			},
			wantSetAside: []string{"p/validate_gen.go"},
		},
		{
			name: "a caller of a declaration that had to go",
			files: map[string]string{
				"p/p.go":            "package p\n\ntype T struct{}\n\nfunc Use(t T) { t.Check(nil) }\n",
				"p/validate_gen.go": header + "package p\n\nfunc (T) Check(Missing) {}\n",
			},
			wantErrorsIn: []string{"p/p.go"},
			wantSetAside: []string{"p/validate_gen.go"},
		},
		{
			name: "a regenerated file that no longer parses",
			files: map[string]string{
				"p/p.go":            "package p\n\ntype T struct{}\n",
				"p/validate_gen.go": header + "package p\n\nfunc (T) Validate( {\n",
			},
			wantSetAside: []string{"p/validate_gen.go"},
		},
		{
			// Two branches generated it with different releases.
			name: "a regenerated file whose marker is in conflict",
			files: map[string]string{
				"p/p.go": "package p\n\ntype T struct{}\n",
				"p/validate_gen.go": "<<<<<<< HEAD\n// Code generated by kanna-validate v0.0.1. DO NOT EDIT.\n=======\n" +
					"// Code generated by kanna-validate v0.0.2. DO NOT EDIT.\n>>>>>>> feature\n\n" +
					"package p\n\nfunc (T) Validate() error { return nil }\n",
			},
			tests:        true,
			wantSetAside: []string{"p/validate_gen.go"},
		},
		{
			name: "a hand-written file in conflict",
			files: map[string]string{
				"p/p.go":            "package p\n\ntype T struct{}\n",
				"p/validate_gen.go": "<<<<<<< HEAD\n=======\n>>>>>>> feature\n\npackage p\n",
			},
			wantErrorsIn: []string{"p/validate_gen.go"},
		},
		{
			name: "a generated file not named as regenerated",
			files: map[string]string{
				"p/p.go":         "package p\n\ntype T struct{}\n",
				"p/other_gen.go": header + "package p\n\nfunc (T) Check(Missing) {}\n",
			},
			wantErrorsIn: []string{"p/other_gen.go"},
		},
		{
			name: "a hand-written file named as regenerated",
			files: map[string]string{
				"p/p.go":            "package p\n\ntype T struct{}\n",
				"p/validate_gen.go": "package p\n\nfunc (T) Check(Missing) {}\n",
			},
			wantErrorsIn: []string{"p/validate_gen.go"},
		},
		{
			// The go command reads validate_gen.go first and blames x.go.
			name: "a package since renamed",
			files: map[string]string{
				"p/x.go":            "package renamed\n\ntype T struct{}\n",
				"p/validate_gen.go": header + "package p\n\nfunc (T) Validate() error { return nil }\n",
			},
			wantSetAside: []string{"p/validate_gen.go"},
		},
		{
			name: "a package since renamed, blaming the generated file",
			files: map[string]string{
				"p/p.go":            "package renamed\n\ntype T struct{}\n",
				"p/validate_gen.go": header + "package p\n\nfunc (T) Validate() error { return nil }\n",
			},
			wantSetAside: []string{"p/validate_gen.go"},
		},
		{
			// Every hand-written file again comes after validate_gen.go.
			name: "a package since renamed, with its tests",
			files: map[string]string{
				"p/x.go":            "package renamed\n\ntype T struct{}\n",
				"p/x_test.go":       "package renamed\n\nimport \"testing\"\n\nfunc TestT(*testing.T) {}\n",
				"p/y_test.go":       "package renamed_test\n\nimport \"testing\"\n\nfunc TestU(*testing.T) {}\n",
				"p/validate_gen.go": header + "package p\n\nfunc (T) Validate() error { return nil }\n",
			},
			tests:        true,
			wantSetAside: []string{"p/validate_gen.go"},
		},
		{
			name: "hand-written files that disagree on their package",
			files: map[string]string{
				"p/x.go":            "package renamed\n",
				"p/y.go":            "package other\n",
				"p/validate_gen.go": header + "package p\n",
			},
			wantErrorsIn: []string{"p/x.go", "p/y.go"},
		},
		{
			// di_gen.go is another generator's to write again, but declaring the
			// old name, it cannot compile here either.
			name: "a package since renamed, with another generator's output",
			files: map[string]string{
				"p/handler.go": "package handler\n\ntype T struct{}\n",
				"p/di_gen.go": "// Code generated by kanna-di. DO NOT EDIT.\n\n" +
					"package hander\n\nfunc NewT() T { return T{} }\n",
				"p/validate_gen.go": header + "package hander\n\nfunc (T) Validate() error { return nil }\n",
			},
			wantSetAside: []string{"p/di_gen.go", "p/validate_gen.go"},
		},
		{
			name: "an error outside the regenerated files",
			files: map[string]string{
				"p/p.go":            "package p\n\ntype T struct{}\n\nvar x int = \"s\"\n",
				"p/validate_gen.go": header + "package p\n\nfunc (T) Validate() error { return nil }\n",
			},
			wantErrorsIn: []string{"p/p.go"},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := module(t, tt.files)
			set := load(t, []string{"./p"}, packages.Config{Dir: dir, Tests: tt.tests, Regenerated: []string{"validate_gen.go"}})

			if got := relative(t, dir, errorFiles(set.Diags)); !slices.Equal(got, tt.wantErrorsIn) {
				t.Errorf("errors in %q, want %q\n%v", got, tt.wantErrorsIn, set.Diags)
			}
			if got := relative(t, dir, set.SetAside); !slices.Equal(got, tt.wantSetAside) {
				t.Errorf("SetAside = %q, want %q", got, tt.wantSetAside)
			}
			for name, want := range tt.files {
				got, err := os.ReadFile(filepath.Clean(filepath.Join(dir, filepath.FromSlash(name))))
				if err != nil {
					t.Fatal(err)
				}
				if string(got) != want {
					t.Errorf("%s changed on disk:\n%s", name, got)
				}
			}
		})
	}
}

// A generated file declaring a package since renamed cannot compile whoever
// regenerates it, so it is set aside for a caller that regenerates nothing too.
func TestLoad_SetsAsideARenamedPackagesOutputWithoutRegenerated(t *testing.T) {
	t.Parallel()

	dir := module(t, map[string]string{
		"p/handler.go": "package handler\n\ntype T struct{}\n",
		"p/di_gen.go":  "// Code generated by kanna-di. DO NOT EDIT.\n\npackage hander\n\nfunc NewT() T { return T{} }\n",
	})

	set := load(t, []string{"./p"}, packages.Config{Dir: dir})
	if len(set.Diags) > 0 {
		t.Errorf("Diags = %v, want none", set.Diags)
	}
	if got, want := relative(t, dir, set.SetAside), []string{"p/di_gen.go"}; !slices.Equal(got, want) {
		t.Errorf("SetAside = %q, want %q", got, want)
	}
}

func TestLoad_SetsNothingAsideWithoutRegenerated(t *testing.T) {
	t.Parallel()

	dir := module(t, map[string]string{
		"p/p.go":            "package p\n\ntype T struct{}\n",
		"p/validate_gen.go": "// Code generated by kanna-validate. DO NOT EDIT.\n\npackage p\n\nfunc (T) Check(Missing) {}\n",
	})

	set := load(t, []string{"./p"}, packages.Config{Dir: dir})
	if got, want := relative(t, dir, errorFiles(set.Diags)), []string{"p/validate_gen.go"}; !slices.Equal(got, want) {
		t.Errorf("errors in %q, want %q", got, want)
	}
	if len(set.SetAside) > 0 {
		t.Errorf("SetAside = %q, want none", set.SetAside)
	}
}
