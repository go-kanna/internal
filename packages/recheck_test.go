// report renders ds as a run in dir writes them, one string each.
func report(dir string, ds []diag.Diag) []string {
	out := make([]string, 0, len(ds))
	for _, d := range ds {
		d.Pos.Filename = diag.ShortPath(dir, d.Pos.Filename)
		out = append(out, d.String())
	}
	return out
}

func TestRecheck(t *testing.T) {
	t.Parallel()

	const (
		gen  = "// Code generated by kanna-x. DO NOT EDIT.\n\n"
		genF = gen + "package p\n\nfunc F() int { return 0 }\n"
	)

	tests := []struct {
		name    string
		files   map[string]string
		pattern string // patterns, separated by spaces
		tests   bool
		write   map[string]string // by path in the module
		remove  []string
		want    []string
	}{
		{
			name:  "a call to what is written",
			files: map[string]string{"p/p.go": "package p\n\nvar _ int = F()\n"},
			write: map[string]string{"p/x_gen.go": genF},
		},
		{
			// go/types checks no further than undefined: F before F is written.
			name:  "a mistake behind a call to what is written",
			files: map[string]string{"p/p.go": "package p\n\nvar _ = F().Bogus\n"},
			write: map[string]string{"p/x_gen.go": genF},
			want:  []string{"p/p.go:3:13: error: F().Bogus undefined (type int has no field or method Bogus)"},
		},
		{
			name:  "a file written again",
			files: map[string]string{"p/p.go": "package p\n\nvar _ int = F()\n", "p/x_gen.go": genF},
			write: map[string]string{"p/x_gen.go": gen + "package p\n\nfunc F() string { return \"\" }\n"},
			want: []string{
				"p/p.go:3:13: error: cannot use F() (value of type string) as int value in variable declaration",
			},
		},
		{
			name:   "a file removed",
			files:  map[string]string{"p/p.go": "package p\n\nvar _ int = F()\n", "p/x_gen.go": genF},
			remove: []string{"p/x_gen.go"},
			want:   []string{"p/p.go:3:13: error: undefined: F"},
		},
		{
			name: "a caller in a root written nothing into",
			files: map[string]string{
				"p/p.go":     "package p\n",
				"p/x_gen.go": genF,
				"q/q.go":     "package q\n\nimport \"example.com/m/p\"\n\nvar _ = p.F()\n",
			},
			pattern: "./...",
			remove:  []string{"p/x_gen.go"},
			want:    []string{"q/q.go:5:11: error: undefined: p.F"},
		},
		{
			// go build stops at p, and so reports nothing of q, whose V has no
			// type once F is gone.
			name: "a root importing one with errors",
			files: map[string]string{
				"p/p.go":     "package p\n\nvar V = F\n",
				"p/x_gen.go": genF,
				"q/q.go":     "package q\n\nimport \"example.com/m/p\"\n\nvar _ = p.V()\n",
			},
			pattern: "./...",
			remove:  []string{"p/x_gen.go"},
			want:    []string{"p/p.go:3:9: error: undefined: F"},
		},
		{
			name: "errors of generated files",
			files: map[string]string{
				"p/p.go":     "package p\n\nvar _ int = F()\n",
				"p/y_gen.go": "// Code generated by kanna-y. DO NOT EDIT.\n\npackage p\n\nvar _ int = \"y\"\n",
			},
			write: map[string]string{"p/x_gen.go": gen + "package p\n\nfunc F() int { return \"x\" }\n"},
		},
		{
			name:  "a file written that does not parse",
			files: map[string]string{"p/p.go": "package p\n\nvar _ = F().Bogus\n"},
			write: map[string]string{"p/x_gen.go": gen + "package p\n\nfunc F( {\n"},
			want:  []string{"p/x_gen.go:5:9: error: the code generated does not parse: expected ')', found '{'"},
		},
		{
			// The file written imports model, which no other file of fixture
			// does.
			name: "an import only a file written makes",
			files: map[string]string{
				"model/model.go":     "package model\n\ntype User struct{}\n",
				"fixture/helpers.go": "package fixture\n\nvar _ = User().Bogus\n",
			},
			pattern: "./...",
			write: map[string]string{
				"fixture/x_gen.go": gen + "package fixture\n\nimport \"example.com/m/model\"\n\n" +
					"func User() model.User { return model.User{} }\n",
			},
			want: []string{
				"fixture/helpers.go:3:16: error: User().Bogus undefined (type model.User has no field or method Bogus)",
			},
		},
		{
			// Of the roots, model alone imports time.
			name: "an import only another root makes",
			files: map[string]string{
				"model/model.go":     "package model\n\nimport \"time\"\n\nvar At time.Time\n",
				"fixture/helpers.go": "package fixture\n\nvar _ = Now().Bogus\n",
			},
			pattern: "./...",
			write: map[string]string{
				"fixture/x_gen.go": gen + "package fixture\n\nimport \"time\"\n\nfunc Now() time.Time { return time.Time{} }\n",
			},
			want: []string{
				"fixture/helpers.go:3:15: error: Now().Bogus undefined (type time.Time has no field or method Bogus)",
			},
		},
		{
			// That net/netip cannot be imported is an error of the file written.
			name:  "an import the load did not read",
			files: map[string]string{"p/p.go": "package p\n\nvar _ = F()\n"},
			write: map[string]string{
				"p/x_gen.go": gen + "package p\n\nimport \"net/netip\"\n\nfunc F() netip.Addr { return netip.Addr{} }\n",
			},
		},
		{
			// newT is declared for the tests alone, which go build leaves out.
			name: "a test variant, and the package built without its tests",
			files: map[string]string{
				"p/p.go":      "package p\n\nvar _ = newT()\n",
				"p/p_test.go": "package p\n\nvar _ int = newT()\n",
			},
			tests: true,
			write: map[string]string{"p/x_gen_test.go": gen + "package p\n\nfunc newT() int { return 0 }\n"},
			want:  []string{"p/p.go:3:9: error: undefined: newT"},
		},
		{
			// The external test imports the test variant, which declares
			// Exported.
			name: "an external test package",
			files: map[string]string{
				"p/p.go":           "package p\n",
				"p/export_test.go": "package p\n\nvar Exported int\n",
				"p/x_test.go": "package p_test\n\nimport \"example.com/m/p\"\n\nvar _ int = p.Exported\n\n" +
					"var _ = Helper().Bogus\n",
			},
			tests: true,
			write: map[string]string{"p/x_gen_test.go": gen + "package p_test\n\nfunc Helper() int { return 0 }\n"},
			want: []string{
				"p/x_test.go:7:18: error: Helper().Bogus undefined (type int has no field or method Bogus)",
			},
		},
		{
			// q passes to r, which is not a root, a T of p checked again.
			name: "a package between two roots",
			files: map[string]string{
				"p/p.go": "package p\n\ntype T struct{}\n",
				"r/r.go": "package r\n\nimport \"example.com/m/p\"\n\nfunc Take(p.T) {}\n",
				"q/q.go": "package q\n\nimport (\n\t\"example.com/m/p\"\n\t\"example.com/m/r\"\n)\n\n" +
					"var _ int = p.F()\n\nfunc f() { r.Take(p.T{}) }\n",
			},
			pattern: "./p ./q",
			write:   map[string]string{"p/x_gen.go": genF},
		},
		{
			// q, which imports r, is not reported on.
			name: "a package between two roots that the changes break",
			files: map[string]string{
				"p/p.go":     "package p\n",
				"p/x_gen.go": genF,
				"r/r.go": "package r\n\nimport \"example.com/m/p\"\n\nvar V = p.F\n\n" +
					"func g() int { return p.F() }\n",
				"q/q.go": "package q\n\nimport \"example.com/m/r\"\n\nvar _ = r.V()\n",
			},
			pattern: "./p ./q",
			remove:  []string{"p/x_gen.go"},
			want:    []string{"r/r.go:5:11: error: undefined: p.F", "r/r.go:7:25: error: undefined: p.F"},
		},
		{
			// x_test imports r as built for the tests of p, against the test
			// variant.
			name: "an external test importing a package that imports the one it tests",
			files: map[string]string{
				"p/p.go":      "package p\n\ntype T struct{}\n",
				"p/p_test.go": "package p\n",
				"p/x_test.go": "package p_test\n\nimport (\n\t\"example.com/m/p\"\n\t\"example.com/m/r\"\n)\n\n" +
					"func f() { r.Take(p.T{}) }\n",
				"r/r.go": "package r\n\nimport \"example.com/m/p\"\n\nfunc Take(p.T) {}\n",
			},
			pattern: "./...",
			tests:   true,
		},
		{
			name: "the go version of the module",
			files: map[string]string{
				"go.mod": "module example.com/m\n\ngo 1.21\n",
				"p/p.go": "package p\n\nvar _ = F()\n\nfunc f() {\n\tfor range 10 {\n\t}\n}\n",
			},
			write: map[string]string{"p/x_gen.go": genF},
			want: []string{
				"p/p.go:6:12: error: cannot range over 10 (untyped int constant): requires go1.22 or later",
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := module(t, tt.files)
			patterns := strings.Fields(cmp.Or(tt.pattern, "./p"))
			set := load(t, patterns, packages.Config{Dir: dir, Tests: tt.tests})
			if blocking, _ := set.Split(); diag.HasErrors(blocking) {
				t.Fatalf("Split() blocks on %v", blocking)
			}

			var changes []output.Change
			for name, src := range tt.write {
				changes = append(changes, output.Change{Path: filepath.Join(dir, name), Data: []byte(src)})
			}
			for _, name := range tt.remove {
				changes = append(changes, output.Change{Path: filepath.Join(dir, name), Remove: true})
			}

			if got := report(dir, packages.Recheck(set, changes)); !slices.Equal(got, tt.want) {
				t.Errorf("Recheck() = %q, want %q", got, tt.want)
			}
		})
	}
}

// What is still to come in a kanna gen is no error of this run, and anything
// else still is. It sets the environment, so it does not run in parallel.
func TestRecheck_Pending(t *testing.T) {
	dir := module(t, map[string]string{"p/p.go": "package p\n\nvar _ = F()\n\nvar _ = G()\n"})
	set := load(t, []string{"./p"}, packages.Config{Dir: dir})

	names := filepath.Join(dir, "pending")
	if err := os.WriteFile(names, []byte("example.com/m/p.F\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Setenv(deps.PendingEnv, names)

	got := report(dir, packages.Recheck(set, nil))
	want := []string{"p/p.go:5:9: error: undefined: G"}
	if !slices.Equal(got, want) {
		t.Errorf("Recheck() = %q, want %q", got, want)
	}
}

func TestRecheck_PendingUnreadable(t *testing.T) {
	dir := module(t, map[string]string{"p/p.go": "package p\n"})
	set := load(t, []string{"./p"}, packages.Config{Dir: dir})

	t.Setenv(deps.PendingEnv, filepath.Join(dir, "gone"))

	if ds := packages.Recheck(set, nil); !diag.HasErrors(ds) {
		t.Errorf("Recheck() = %v, want an error for a file it cannot read", ds)
	}
}
