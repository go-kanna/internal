package packages_test

import (
	"path/filepath"
	"slices"
	"testing"

	"github.com/go-kanna/internal/output"
	"github.com/go-kanna/internal/packages"
)

func TestDependents(t *testing.T) {
	t.Parallel()

	const msgs = "package msgs\n\nfunc Hello() string { return \"hello\" }\n"
	dir := module(t, map[string]string{
		"msgs/msgs.go":        msgs,
		"msgs/ext_test.go":    "package msgs_test\n\nimport \"example.com/m/msgs\"\n\nvar _ = msgs.Hello\n",
		"a/a.go":              "package a\n\nimport \"example.com/m/msgs\"\n\nvar Hi = msgs.Hello\n",
		"b/b.go":              "package b\n\nimport \"example.com/m/a\"\n\nvar _ = a.Hi\n",
		"t/t.go":              "package t\n",
		"t/t_test.go":         "package t\n\nimport \"example.com/m/msgs\"\n\nvar _ = msgs.Hello\n",
		"x/x_test.go":         "package x_test\n\nimport \"example.com/m/msgs\"\n\nvar _ = msgs.Hello\n",
		"unrelated/u.go":      "package unrelated\n",
		"unrelated/u_test.go": "package unrelated\n",
	})

	got, err := packages.Dependents(dir, "example.com/m/msgs")
	if err != nil {
		t.Fatal(err)
	}
	// msgs itself, whose external test imports it, is not among them.
	want := []string{"example.com/m/a", "example.com/m/b", "example.com/m/t", "example.com/m/x"}
	if !slices.Equal(got, want) {
		t.Errorf("Dependents() = %q, want %q", got, want)
	}
}

func TestDependents_ErrorWhenTheGoCommandCannotRun(t *testing.T) {
	t.Parallel()

	if _, err := packages.Dependents(filepath.Join(t.TempDir(), "missing"), "example.com/m/msgs"); err == nil {
		t.Error("Dependents() in a missing directory succeeded, want an error")
	}
}

func TestSet_Introduced(t *testing.T) {
	t.Parallel()

	// q calls what x_gen.go declares, which the run removes; p had an error of
	// its own before the run.
	const gen = "// Code generated by kanna-x. DO NOT EDIT.\n\npackage q\n\nfunc F() int { return 0 }\n"
	dir := module(t, map[string]string{
		"p/p.go":     "package p\n\nvar _ int = \"s\"\n",
		"q/q.go":     "package q\n\nvar _ = F()\n",
		"q/x_gen.go": gen,
	})
	set := load(t, []string{"./..."}, packages.Config{Dir: dir})

	rds := packages.Recheck(set, []output.Change{{Path: filepath.Join(dir, "q", "x_gen.go"), Remove: true}})
	if got, want := where(t, dir, rds), []string{"p/p.go:3:13", "q/q.go:3:9"}; !slices.Equal(got, want) {
		t.Fatalf("Recheck() at %q, want %q", got, want)
	}
	if got, want := where(t, dir, set.Introduced(rds)), []string{"q/q.go:3:9"}; !slices.Equal(got, want) {
		t.Errorf("Introduced() at %q, want %q", got, want)
	}
}
