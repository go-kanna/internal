package gofile_test

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"strings"
	"testing"
)

func TestFile_Bytes(t *testing.T) {
	t.Parallel()

	f := newFile()
	f.Reserve("log")
	model := f.Import("example.com/app/model", "model")
	yaml := f.Import("gopkg.in/yaml.v3", "yaml")
	errs := f.Import("errors", "errors")
	log := f.Import("example.com/log2", "log")
	fmt.Fprintf(f, "func (u User) Model()  %s.User {\nreturn %s.User{}\n}\n", model, model)
	fmt.Fprintf(f, "var _, _, _ = %s.Marshal, %s.New, %s.Print\n", yaml, errs, log)

	got, err := f.Bytes()
	if err != nil {
		t.Fatalf("Bytes() error = %v", err)
	}

	// gofmt has laid out the body, and the imports are grouped. "log2" ends the
	// path but the package declares log, so the name is spelled out.
	want := `// Code generated by kanna-test. DO NOT EDIT.

package user

import (
	"errors"

	"example.com/app/model"
	log2 "example.com/log2"
	yaml "gopkg.in/yaml.v3"
)

func (u User) Model() model.User {
	return model.User{}
}

var _, _, _ = yaml.Marshal, errors.New, log2.Print
`
	if string(got) != want {
		t.Errorf("Bytes():\n%s\nwant:\n%s", got, want)
	}
}

func TestFile_BytesIsGenerated(t *testing.T) {
	t.Parallel()

	got, err := newFile().Bytes()
	if err != nil {
		t.Fatalf("Bytes() error = %v", err)
	}

	file, err := parser.ParseFile(token.NewFileSet(), "user_gen.go", got, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	if !ast.IsGenerated(file) {
		t.Errorf("Bytes() is not marked generated:\n%s", got)
	}
	if strings.Contains(string(got), "import") {
		t.Errorf("Bytes() has an import block with nothing to import:\n%s", got)
	}
}

func TestFile_BytesThatDoNotParse(t *testing.T) {
	t.Parallel()

	f := newFile()
	fmt.Fprint(f, "func broken( {\n")

	got, err := f.Bytes()
	if err == nil {
		t.Fatal("Bytes() succeeded on source that does not parse")
	}
	if !strings.Contains(string(got), "func broken( {") {
		t.Errorf("Bytes() = %q, want the source that failed", got)
	}
}
