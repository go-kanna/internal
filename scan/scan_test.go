func structs(t *testing.T, files map[string]string) []scan.Struct {
	t.Helper()

	return scan.Structs([]*packages.Package{pkgtest.Load(t, files)})
}

func names(ss []scan.Struct) []string {
	out := make([]string, 0, len(ss))
	for _, s := range ss {
		out = append(out, s.Name)
	}
	return out
}

func find(t *testing.T, ss []scan.Struct, name string) scan.Struct {
	t.Helper()

	i := slices.IndexFunc(ss, func(s scan.Struct) bool { return s.Name == name })
	if i < 0 {
		t.Fatalf("no struct %s among %q", name, names(ss))
	}
	return ss[i]
}

// text joins the lines of cg as written, directives included.
func text(cg *ast.CommentGroup) string {
	if cg == nil {
		return ""
	}
	lines := make([]string, 0, len(cg.List))
	for _, c := range cg.List {
		lines = append(lines, c.Text)
	}
	return strings.Join(lines, "\n")
}

func TestStructs_DeclarationOrder(t *testing.T) {
	t.Parallel()

	got := structs(t, map[string]string{
		"a.go": "package p\n\ntype Zebra struct{}\n\ntype Apple struct{}\n",
		"b.go": "package p\n\ntype Mango struct{}\n",
	})

	if want := []string{"Zebra", "Apple", "Mango"}; !slices.Equal(names(got), want) {
		t.Errorf("structs = %q, want %q", names(got), want)
	}
}

func TestStructs_PackageByPackage(t *testing.T) {
	t.Parallel()

	got := scan.Structs([]*packages.Package{
		pkgtest.Load(t, map[string]string{"b.go": "package second\n\ntype B struct{}\n"}),
		pkgtest.Load(t, map[string]string{"a.go": "package first\n\ntype A struct{}\n"}),
	})

	if want := []string{"B", "A"}; !slices.Equal(names(got), want) {
		t.Errorf("structs = %q, want %q", names(got), want)
	}
	if got[0].PkgPath != "second" || got[0].PkgName != "second" {
		t.Errorf("B is in %s (%s), want second", got[0].PkgPath, got[0].PkgName)
	}
}

func TestStructs_OnlyStructTypes(t *testing.T) {
	t.Parallel()

	got := structs(t, map[string]string{"p.go": `package p

type Exported struct{}

type unexported struct{}

type Generic[T any] struct{ V T }

type Alias = Exported

type ID int

type Reader interface{ Read() }

type _ struct{}

func f() {
	type local struct{}
	_ = local{}
}
`})

	if want := []string{"Exported", "unexported", "Generic"}; !slices.Equal(names(got), want) {
		t.Errorf("structs = %q, want %q", names(got), want)
	}
	if find(t, got, "Generic").Named.TypeParams().Len() != 1 {
		t.Error("Generic has no type parameter")
	}
}

func TestStructs_SkipsGeneratedFiles(t *testing.T) {
	t.Parallel()

	// The marker counts wherever Go counts it: below a license header or a
	// build constraint, but not on a doc comment further down.
	tests := []struct {
		name   string
		header string
		want   []string
	}{
		{name: "marker alone", header: "// Code generated by kanna-x. DO NOT EDIT.\n\n", want: nil},
		{name: "below a copyright line", header: "// Copyright 2026\n// Code generated by kanna-x. DO NOT EDIT.\n\n"},
		{name: "below a build constraint", header: "//go:build !ignore\n\n// Code generated by kanna-x. DO NOT EDIT.\n\n"},
		{name: "no marker", header: "", want: []string{"Second"}},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			got := structs(t, map[string]string{
				"a.go": "package p\n\n// First mentions the marker below, which makes no file generated.\n" +
					"// Code generated by kanna-x. DO NOT EDIT.\ntype First struct{}\n",
				"b.go": tt.header + "package p\n\ntype Second struct{}\n",
			})

			if want := append([]string{"First"}, tt.want...); !slices.Equal(names(got), want) {
				t.Errorf("structs = %q, want %q", names(got), want)
			}
		})
	}
}

func TestStructs_Fields(t *testing.T) {
	t.Parallel()

	got := structs(t, map[string]string{"p.go": "package p\n\nimport \"time\"\n\ntype Base struct{}\n\n" +
		"type T struct {\n" +
		"\tName  string `json:\"name\" validate:\"required\"`\n" +
		"\tlower int\n" +
		"\tBase\n" +
		"\t*time.Location\n" +
		"\t_ Base `di:\"arg\"`\n" +
		"}\n"})

	type field struct {
		name, typ, tag     string
		line               int
		exported, embedded bool
	}
	t0 := find(t, got, "T")
	fields := make([]field, 0, len(t0.Fields))
	for _, f := range t0.Fields {
		fields = append(fields, field{
			name: f.Name, typ: f.Type.String(), tag: string(f.Tag),
			line: f.Pos.Line, exported: f.Exported, embedded: f.Embedded,
		})
	}

	want := []field{
		{name: "Name", typ: "string", tag: `json:"name" validate:"required"`, line: 8, exported: true},
		{name: "lower", typ: "int", line: 9},
		{name: "Base", typ: "p.Base", line: 10, exported: true, embedded: true},
		{name: "Location", typ: "*time.Location", line: 11, exported: true, embedded: true},
		// A blank field is how di declares an argument; it must not drop out.
		{name: "_", typ: "p.Base", tag: `di:"arg"`, line: 12},
	}
	if !slices.Equal(fields, want) {
		t.Errorf("fields:\n%+v\nwant:\n%+v", fields, want)
	}
}

func TestStructs_Doc(t *testing.T) {
	t.Parallel()

	got := structs(t, map[string]string{"p.go": `package p

// One is documented.
//
//kanna:validate
type One struct{}

// The group is documented as a whole.
type (
	// Two is documented on its own.
	Two struct{}

	Three struct{}
)

type Four struct{}
`})

	tests := []struct {
		name string
		want string
	}{
		{name: "One", want: "// One is documented.\n//\n//kanna:validate"},
		{name: "Two", want: "// Two is documented on its own."},
		{name: "Three", want: ""},
		{name: "Four", want: ""},
	}
	for _, tt := range tests {
		if got := text(find(t, got, tt.name).Doc); got != tt.want {
			t.Errorf("%s.Doc = %q, want %q", tt.name, got, tt.want)
		}
	}
}

func TestStructs_Position(t *testing.T) {
	t.Parallel()

	got := find(t, structs(t, map[string]string{"p.go": "package p\n\n\ntype T struct{}\n"}), "T")

	if got.Pos.Filename != "p.go" || got.Pos.Line != 4 || got.Pos.Column != 6 {
		t.Errorf("Pos = %v, want p.go:4:6", got.Pos)
	}
}
