// Package gofile assembles the source of one generated Go file: the header that
// marks it generated, the package clause, the imports, and the body.
//
// Every name the file introduces comes from one place. An import is named so
// that it collides neither with what the package declares nor with a local
// variable of the body, and a local variable is named so that it shadows no
// import. Getting either wrong yields a file that does not compile, or one that
// compiles against the wrong package. Neither is ever a keyword or a
// predeclared identifier such as error, which the body spells out.
package gofile

import (
	"bytes"
	"cmp"
	"fmt"
	"go/format"
	"maps"
	"path"
	"runtime/debug"
	"slices"
	"strings"

	"golang.org/x/mod/module"
	"golang.org/x/mod/semver"
)

// readBuildInfo is replaced in tests, which cannot build a release.
var readBuildInfo = debug.ReadBuildInfo

// File is one generated file under construction. Its body is written to it as
// to any io.Writer; Bytes puts the file together.
type File struct {
	generator string
	pkgPath   string
	pkgName   string
	body      bytes.Buffer

	// imports maps the path of each imported package to its spec.
	imports map[string]importSpec

	// file holds the names in the file's scope: reserved ones and imports.
	file map[string]bool

	// locals holds every name a Scope has handed out.
	locals map[string]bool
}

type importSpec struct {
	name  string // the name the package declares
	local string // the name the file refers to it by
}

// New starts a file that generator, such as "kanna-validate", writes into the
// package pkgName at pkgPath.
func New(generator, pkgPath, pkgName string) *File {
	return &File{
		generator: generator,
		pkgPath:   pkgPath,
		pkgName:   pkgName,
		imports:   make(map[string]importSpec),
		file:      make(map[string]bool),
		locals:    make(map[string]bool),
	}
}

// Write appends p to the body. It never fails.
func (f *File) Write(p []byte) (int, error) {
	f.body.Write(p)
	return len(p), nil
}

// Bytes returns the file formatted by gofmt. When the source does not parse,
// it is returned unformatted along with gofmt's error, to show what went wrong;
// the caller says which file it is. The header names the generator's release
// when the binary is one.
func (f *File) Bytes() ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by %s. DO NOT EDIT.\n\npackage %s\n\n", generatedBy(f.generator), f.pkgName)
	f.writeImports(&b)
	b.Write(f.body.Bytes())

	src, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), err
	}
	return src, nil
}

// generatedBy names generator, followed by the version of its release when the
// binary is one, so that a file another release generated shows in review. Any
// other build leaves the version out, as go run, go test, or a build from a
// checkout reports "(devel)", a pseudo-version, or a tag marked +dirty: none
// names a release, and each would change every generated file in passing.
func generatedBy(generator string) string {
	info, ok := readBuildInfo()
	if !ok {
		return generator
	}
	v := info.Main.Version
	if !semver.IsValid(v) || module.IsPseudoVersion(v) || semver.Build(v) != "" {
		return generator
	}
	return generator + " " + v
}

// ModuleImports returns, sorted, the paths the file imports from modules, which
// is every one outside the standard library: what the go.mod of the package it
// goes into has to provide.
func (f *File) ModuleImports() []string {
	var paths []string
	for p := range f.imports {
		if !standard(p) {
			paths = append(paths, p)
		}
	}
	slices.Sort(paths)
	return paths
}

// writeImports writes the import block, with the standard library above the
// rest. The local name is left out only when it is the name the package
// declares and the import path ends in that name, so that a reader never has to
// look up what a path imports as.
func (f *File) writeImports(b *bytes.Buffer) {
	if len(f.imports) == 0 {
		return
	}

	paths := slices.SortedFunc(maps.Keys(f.imports), func(a, b string) int {
		return cmp.Or(cmp.Compare(group(a), group(b)), strings.Compare(a, b))
	})

	b.WriteString("import (\n")
	for i, p := range paths {
		if i > 0 && group(p) != group(paths[i-1]) {
			b.WriteString("\n")
		}
		if spec := f.imports[p]; spec.local == spec.name && spec.name == path.Base(p) {
			fmt.Fprintf(b, "\t%q\n", p)
		} else {
			fmt.Fprintf(b, "\t%s %q\n", spec.local, p)
		}
	}
	b.WriteString(")\n\n")
}

// group puts the standard library before everything else.
func group(importPath string) int {
	if standard(importPath) {
		return 0
	}
	return 1
}

// standard reports whether importPath is in the standard library, whose paths
// have no dot in their first element.
func standard(importPath string) bool {
	first, _, _ := strings.Cut(importPath, "/")
	return !strings.Contains(first, ".")
}
